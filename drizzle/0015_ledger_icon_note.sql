-- 0015：账本支持「图标」与「备注」
--
-- ## 现象
-- 账本管理页只能改名字，账本卡片上一律是同一个默认图标，
-- 没有任何地方能写「这本账是记什么的」。多本账并存时（家庭账 / 装修账 /
-- 生意账），用户靠名字区分，名字一旦接近就认错。
--
-- ## 为什么必须是可空列
-- `ALTER TABLE ... ADD COLUMN NOT NULL DEFAULT` 对**已有行不填默认值**，
-- 会在下一次 INSERT 时报 NOT NULL 约束错误。账本表是账螅入口表，
-- 注册后第一件事就是建账本 —— 迁移漏填会让注册链路整体 500。
-- 所以这里一律加可空列，缺省由业务层 `?? ''` 兜底。
--
-- ## 为什么不给存量账本回填具体值
-- 图标是**用户偏好**，不是可推导的事实。回填任何具体图标都等于替用户做了
-- 一个他没表达的选择；留 NULL 由前端按账本类型回退默认图标，语义等价且
-- 不侵占用户后续的选择权。
--
-- ## 回滚
-- SQLite 不支持 DROP COLUMN（3.35 以下）。需要回滚时重建表，或者直接保留
-- 这两列 —— 可空且无索引，保留不影响任何查询。
-- ==========================================================================
